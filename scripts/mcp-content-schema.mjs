/**
 * The build's own content rules (src/content/config.ts), bundled for the server, so the SOARD connection for Claude
 * checks a page change exactly as the build will before saving it: a change the build would refuse (a Press story
 * with a category that isn't one of five, an event with no date) is never saved, so it can never stop a Publish.
 *
 * config.ts imports `astro:content` only for `defineCollection` and `z`; here those are a pass-through and Zod
 * itself. The output is committed (functions/api/_mcp/content-schema.gen.js) and tests/mcp.test.mjs rebuilds it to
 * prove it still matches config.ts: after changing config.ts, run `node scripts/mcp-content-schema.mjs`.
 */

import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'functions/api/_mcp/content-schema.gen.js');

const SHIM = `export const defineCollection = (c) => c;\nexport { z } from 'zod';\n`;
const HEADER = '// Generated by scripts/mcp-content-schema.mjs from src/content/config.ts: never edit by hand.\n';

/** The bundle's text */
export async function contentSchemaSource() {
  const r = await build({
    entryPoints: [join(ROOT, 'src/content/config.ts')],
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true, legalComments: 'none', write: false, logLevel: 'silent',
    mainFields: ['module', 'main'], absWorkingDir: ROOT,
    plugins: [{
      name: 'astro-content',
      setup(b) {
        b.onResolve({ filter: /^astro:content$/ }, () => ({ path: 'astro-content-shim', namespace: 'shim' }));
        b.onLoad({ filter: /.*/, namespace: 'shim' }, () => ({ contents: SHIM, resolveDir: ROOT, loader: 'js' }));
      },
    }],
  });
  return HEADER + r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await contentSchemaSource();
  await writeFile(OUT, text);
  console.log(`[mcp-content-schema] ${OUT.slice(ROOT.length + 1)}: ${Math.round(text.length / 1024)} KB`);
}
